"""Fake cameras: loop video files as password-protected RTSP cameras.

Each file in testdata/ becomes one camera with two streams, like an Annke:
    <id>_main  the file as-is (no re-encode)
    <id>_sub   re-encoded to 640px H.264 (a typical substream)

The streams are served by a separate go2rtc ("fakecam" service), so the real
stack connects to them exactly as it would to cameras on the network.
Replaying the same clips makes detection results repeatable, which is what
we need to compare against Frigate later.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

VIDEO_EXTS = {".mp4", ".mkv", ".mov", ".avi", ".ts"}

HEADER = """\
# GENERATED by `docker compose run --rm tools fakecam` from the files in testdata/.
"""

LOOP = "ffmpeg -hide_banner -v error -re -stream_loop -1 -i {path}"
MAIN = LOOP + " -c copy -rtsp_transport tcp -f rtsp {{output}}"
# The substream is transcoded from the main stream inside go2rtc, so both show the same
# moment, like a real camera. (Two separate loops of the file would drift apart.)
SUB = "ffmpeg:{cid}_main#video=h264#width=640"


def camera_id_for(path: Path) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", path.stem.lower()).strip("_")
    if not slug or not slug[0].isalpha():
        slug = f"cam_{slug}".rstrip("_")
    slug = slug[:28]
    return slug[:-4] + "_cam" if slug.endswith("_sub") else slug


def find_videos(testdata: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for p in sorted(testdata.iterdir()) if testdata.exists() else []:
        if p.is_file() and p.suffix.lower() in VIDEO_EXTS:
            cid = camera_id_for(p)
            n = 2
            while cid in found:
                cid = f"{camera_id_for(p)}_{n}"
                n += 1
            found[cid] = p
    return found


def build_fakecam_config(videos: dict[str, Path], container_dir: str = "/testdata") -> dict:
    streams = {}
    for cid, p in videos.items():
        path = f"{container_dir}/{p.name}"
        if " " in path:
            path = f'"{path}"'
        streams[f"{cid}_main"] = f"exec:{MAIN.format(path=path)}"
        streams[f"{cid}_sub"] = SUB.format(cid=cid)
    return {
        "api": {"listen": ":1984"},
        # Same login as the real cameras; go2rtc expands these from .env.
        "rtsp": {"listen": ":8554", "username": "${CAM_USER}", "password": "${CAM_PASSWORD}"},
        "webrtc": {"listen": ""},
        "streams": streams,
    }


def cameras_yaml(videos: dict[str, Path], host: str = "fakecam") -> str:
    lines = [
        "# Fake cameras generated from testdata/ (see README: Testing without cameras).",
        "storage:",
        "  retention_days: 3",
        "cameras:",
    ]
    for cid, p in videos.items():
        base = f"rtsp://${{CAM_USER}}:${{CAM_PASSWORD}}@{host}:8554/{cid}"
        lines += [
            f"  {cid}:",
            f"    name: {p.stem}",
            "    streams:",
            f"      main: {base}_main",
            f"      sub: {base}_sub",
        ]
    return "\n".join(lines) + "\n"


def write_fakecam(testdata: Path, config_dir: Path) -> tuple[dict[str, Path], Path, Path | None]:
    """Write the fakecam go2rtc config; write cameras.yml only if none exists yet.

    Returns (videos, fakecam_config_path, cameras_yml_path_or_None).
    """
    videos = find_videos(testdata)
    out = config_dir / "generated" / "fakecam"
    out.mkdir(parents=True, exist_ok=True)
    cfg_path = out / "go2rtc.yaml"
    cfg_path.write_text(
        HEADER + yaml.safe_dump(build_fakecam_config(videos), sort_keys=False, width=1000),
        encoding="utf-8",
    )
    cams = config_dir / "cameras.yml"
    if videos and not cams.exists():
        cams.write_text(cameras_yaml(videos), encoding="utf-8")
        return videos, cfg_path, cams
    return videos, cfg_path, None
